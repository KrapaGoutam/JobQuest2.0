import { api, type PublicSession } from '../api';
import type { AutomationSetupView, ProviderSchedulerStatus } from '../lib/aiScheduler';
import { formToBody, summarizeAutomations, type AutomationFormState, type AutomationOverview, type AutomationRunView, type AutomationView } from '../lib/aiAutomation';

// Automation definitions talk to the JobQuest API only (never MCP): reads are bearer-authenticated GETs; every
// mutation is a CSRF-protected POST that the server re-validates from scratch (workspace and owner come from the
// verified session, never from the body).

export class AutomationApiError extends Error {
  constructor(public code: string, message: string, public field: string | null = null) {
    super(message);
  }
}

type Err = { error?: { code?: string; message?: string; field?: string } };
const fail = (r: { status: number; data: Err }): never => {
  throw new AutomationApiError(r.data.error?.code ?? 'SAVE_FAILED', r.data.error?.message ?? 'Request failed.', r.data.error?.field ?? null);
};
const token = (s: PublicSession | null) => s?.access_token;

export async function fetchAutomations(workspaceId: string, session: PublicSession | null): Promise<AutomationView[]> {
  const r = await api<{ automations: AutomationView[] } & Err>(`/ai/automations?workspace_id=${encodeURIComponent(workspaceId)}`, undefined, token(session));
  return r.status === 200 ? r.data.automations : fail(r);
}

/** Create (id null) or update. Returns the saved automation's id. */
export async function saveAutomation(
  workspaceId: string, session: PublicSession | null, id: string | null, form: AutomationFormState,
): Promise<{ id: string; created: boolean }> {
  const r = await api<{ id: string; created: boolean } & Err>(id ? `/ai/automations/${encodeURIComponent(id)}` : '/ai/automations', { workspace_id: workspaceId, ...formToBody(form) }, token(session));
  return r.status === 200 || r.status === 201 ? r.data : fail(r);
}

export async function deleteAutomation(workspaceId: string, session: PublicSession | null, id: string): Promise<void> {
  const r = await api<{ id: string } & Err>(`/ai/automations/${encodeURIComponent(id)}/delete`, { workspace_id: workspaceId }, token(session));
  if (r.status !== 200) fail(r);
}

/** Recent runs of one automation (scheduled / manual / retry), newest first. */
export async function fetchAutomationRuns(workspaceId: string, session: PublicSession | null, id: string): Promise<AutomationRunView[]> {
  const r = await api<{ runs: AutomationRunView[] } & Err>(`/ai/automations/${encodeURIComponent(id)}/runs?workspace_id=${encodeURIComponent(workspaceId)}`, undefined, token(session));
  return r.status === 200 ? r.data.runs : fail(r);
}

/** Run Now. `clientKey` makes a double click or a retried request the same execution. Only called when the server says ready. */
export async function runAutomationNow(workspaceId: string, session: PublicSession | null, id: string, clientKey: string): Promise<{ runId: string; created: boolean; status: string }> {
  const r = await api<{ runId: string; created: boolean; status: string } & Err>(`/ai/automations/${encodeURIComponent(id)}/run-now`, { workspace_id: workspaceId, client_key: clientKey }, token(session));
  return r.status === 200 || r.status === 201 ? r.data : fail(r);
}

/** Overview card data; isolated by the caller so a failure never breaks the rest of the Overview. */
export async function fetchAutomationOverview(workspaceId: string, session: PublicSession | null): Promise<AutomationOverview> {
  return summarizeAutomations(await fetchAutomations(workspaceId, session));
}

/** AI-11G: connection and scheduled-execution state per provider (separate facts). */
export async function fetchSchedulerStatus(workspaceId: string, session: PublicSession | null): Promise<ProviderSchedulerStatus[]> {
  const r = await api<{ providers: ProviderSchedulerStatus[] } & Err>(`/ai/automations/scheduler-status?workspace_id=${encodeURIComponent(workspaceId)}`, undefined, token(session));
  return r.status === 200 ? r.data.providers : fail(r);
}

/** AI-11G: copyable provider-setup instructions generated by the server from the stored automation. */
export async function fetchAutomationSetup(workspaceId: string, session: PublicSession | null, id: string): Promise<AutomationSetupView> {
  const r = await api<AutomationSetupView & Err>(`/ai/automations/${encodeURIComponent(id)}/setup?workspace_id=${encodeURIComponent(workspaceId)}`, undefined, token(session));
  return r.status === 200 ? { setup: r.data.setup, status: r.data.status } : fail(r);
}
