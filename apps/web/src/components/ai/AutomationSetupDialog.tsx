import { useEffect, useState, type CSSProperties } from 'react';
import { Check, Copy } from 'lucide-react';
import type { PublicSession } from '../../api';
import { fetchAutomationSetup } from '../../api/aiAutomations';
import { formatInZone, type AutomationView } from '../../lib/aiAutomation';
import {
  RUN_IN_PROVIDER_HELP, connectionLabel, scheduleTimingNotes, schedulerView, type AutomationSetupView as SetupData,
} from '../../lib/aiScheduler';
import { Button } from '../ui/Button';
import { Dialog } from '../ui/Dialog';
import { StatusBadge } from '../ui/StatusBadge';

// AI-11G: copyable provider setup for ONE automation. JobQuest cannot create a schedule inside Claude, ChatGPT or Gemini, and it
// holds no provider credential: the instructions are generated by the server from the stored automation (public-safe id only),
// the user pastes them into the provider's own scheduled task, and the provider pulls work from JobQuest by claiming it.

export type SetupMode = 'setup' | 'manual';
export type SetupLoad = { status: 'loading' } | { status: 'error'; message: string } | { status: 'ready'; data: SetupData };

const stack: CSSProperties = { display: 'grid', gap: '14px' };
const small: CSSProperties = { fontSize: '13px' };
const pre: CSSProperties = {
  margin: '6px 0 0', padding: '10px', border: '1px solid var(--color-border)', borderRadius: '8px', fontSize: '12px', lineHeight: 1.5,
  whiteSpace: 'pre-wrap', overflowWrap: 'anywhere', maxHeight: '260px', overflow: 'auto', background: 'var(--color-surface-2, transparent)',
};

export interface SetupBodyProps { data: SetupData; mode: SetupMode; copied: string | null; copyError: string | null; onCopy(which: 'scheduled' | 'manual', text: string): void; /** Loads fresh run-once instructions (a NEW run key) for another attended run. */ onNewRun?(): void; /** The stored automation (timing notes only). */ automation?: AutomationView }

/** Presentational (server-rendered in tests): readiness, schedule to match, steps, both instruction sets, validation. */
export function AutomationSetupBody({ data, mode, copied, copyError, onCopy, onNewRun, automation }: SetupBodyProps) {
  const { setup, status } = data;
  const view = schedulerView(status, { hasAutomation: true });
  const copyButton = (which: 'scheduled' | 'manual', text: string, label: string) => (
    <Button size="sm" variant="secondary" onClick={() => onCopy(which, text)} leftIcon={copied === which ? <Check size={14} /> : <Copy size={14} />}>
      {copied === which ? 'Copied' : label}
    </Button>
  );
  return (
    <div style={stack} data-testid="automation-setup">
      <div style={{ display: 'grid', gap: '4px' }}>
        <div style={{ display: 'flex', flexWrap: 'wrap', gap: '8px', alignItems: 'center' }}>
          <b>{setup.providerLabel}</b>
          <StatusBadge variant={view.variant}>Scheduled execution: {view.label}</StatusBadge>
        </div>
        <span className="muted" style={small}>JobQuest connection: {connectionLabel(status)}</span>
        <span className="muted" style={small}>{view.help}</span>
      </div>
      <dl style={{ display: 'grid', gridTemplateColumns: 'auto 1fr', gap: '2px 12px', margin: 0, fontSize: '13px' }}>
        <dt className="muted">Automation</dt><dd style={{ margin: 0, overflowWrap: 'anywhere' }}>{setup.automationName}</dd>
        <dt className="muted">Automation ID</dt><dd style={{ margin: 0, overflowWrap: 'anywhere' }}><code>{setup.automationId}</code></dd>
        <dt className="muted">Schedule to match</dt><dd style={{ margin: 0 }}>{setup.scheduleSummary}</dd>
      </dl>
      {automation && (
        <ul style={{ margin: 0, paddingLeft: '20px', ...small }} data-testid="schedule-timing-notes" aria-label="When this runs">
          {scheduleTimingNotes({ enabled: automation.enabled, cadence: automation.cadence, timezone: automation.timezone, nextExpectedRunAt: automation.state.nextExpectedRunAt }, formatInZone).map((n, i) => <li key={i}>{n}</li>)}
        </ul>
      )}
      <div>
        <b style={small}>Steps (in order)</b>
        <ol style={{ margin: '4px 0 0', paddingLeft: '20px', ...small }}>{setup.planSteps.map((s) => <li key={s.order}>{s.title}{s.title === 'Daily Digest' ? ' (composed by JobQuest, last)' : ''}</li>)}</ol>
      </div>

      <details open={mode === 'setup'}>
        <summary style={{ cursor: 'pointer', fontWeight: 600 }}>1. Create the schedule in {setup.providerLabel}</summary>
        <ol style={{ margin: '6px 0 0', paddingLeft: '20px', ...small }}>{setup.providerSteps.map((s, i) => <li key={i}>{s}</li>)}</ol>
        <div style={{ marginTop: '8px' }}>{copyButton('scheduled', setup.scheduledInstructions, 'Copy scheduled-task instructions')}</div>
        <pre style={pre} tabIndex={0} aria-label="Scheduled-task instructions">{setup.scheduledInstructions}</pre>
      </details>

      <details open={mode === 'manual'}>
        <summary style={{ cursor: 'pointer', fontWeight: 600 }}>2. Run in {setup.providerLabel} once, now</summary>
        <p className="muted" style={{ margin: '6px 0 0', ...small }}>{RUN_IN_PROVIDER_HELP}</p>
        <p className="muted" style={{ margin: '6px 0 0', ...small }} data-testid="manual-key-note">
          These instructions carry a run key (<code>{setup.manualRunKey}</code>) generated by JobQuest. Pasting the <b>same</b> text again, even in a new chat, is safe: it is the same run and is never duplicated. To run it a second time on purpose, get new instructions.
        </p>
        <div style={{ marginTop: '8px', display: 'flex', flexWrap: 'wrap', gap: '8px' }}>
          {copyButton('manual', setup.manualRunInstructions, 'Copy run-once instructions')}
          {onNewRun && <Button size="sm" variant="secondary" onClick={onNewRun}>New run (new key)</Button>}
        </div>
        <pre style={pre} tabIndex={0} aria-label="Run-once instructions">{setup.manualRunInstructions}</pre>
      </details>

      <details>
        <summary style={{ cursor: 'pointer', fontWeight: 600 }}>3. Validate it</summary>
        <ol style={{ margin: '6px 0 0', paddingLeft: '20px', ...small }}>{setup.validationSteps.map((s, i) => <li key={i}>{s}</li>)}</ol>
      </details>

      {setup.limitations.length > 0 && (
        <details>
          <summary style={{ cursor: 'pointer', fontWeight: 600 }}>What is and isn’t known about {setup.providerLabel}</summary>
          <ul style={{ margin: '6px 0 0', paddingLeft: '20px', ...small }}>{setup.limitations.map((s, i) => <li key={i}>{s}</li>)}</ul>
        </details>
      )}
      <p role="status" aria-live="polite" className="muted" style={{ margin: 0, ...small }}>{copyError ?? (copied ? 'Copied to the clipboard.' : '')}</p>
    </div>
  );
}

export function AutomationSetupDialog({ workspaceId, session, automation, mode, onClose }: {
  workspaceId: string; session: PublicSession; automation: AutomationView; mode: SetupMode; onClose(): void;
}) {
  const [load, setLoad] = useState<SetupLoad>({ status: 'loading' });
  const [copied, setCopied] = useState<string | null>(null);
  const [copyError, setCopyError] = useState<string | null>(null);
  const [version, setVersion] = useState(0);
  useEffect(() => {
    let live = true;
    setLoad({ status: 'loading' });
    setCopied(null);
    fetchAutomationSetup(workspaceId, session, automation.id).then(
      (data) => live && setLoad({ status: 'ready', data }),
      (e) => live && setLoad({ status: 'error', message: e instanceof Error ? e.message : 'Couldn’t load the setup instructions.' }),
    );
    return () => { live = false; };
  }, [workspaceId, automation.id, session.access_token, version]);

  const onCopy = async (which: 'scheduled' | 'manual', text: string) => {
    setCopyError(null);
    try {
      if (!navigator.clipboard?.writeText) throw new Error('clipboard unavailable');
      await navigator.clipboard.writeText(text);
      setCopied(which);
    } catch { setCopied(null); setCopyError('Copy failed. Select the text in the box and copy it manually.'); }
  };

  const label = load.status === 'ready' ? load.data.setup.providerLabel : automation.provider;
  return (
    <Dialog
      isOpen
      onClose={onClose}
      title={mode === 'manual' ? `Run “${automation.name}” in ${label}` : `Set up “${automation.name}” in ${label}`}
      description="JobQuest can’t create schedules in your provider or start its runs. Paste these instructions into the provider; it asks JobQuest for the work, so nothing here contains a credential."
      maxWidth={720}
      footer={<><span className="grow" /><Button variant="primary" onClick={onClose}>Done</Button></>}
    >
      {load.status === 'loading' && <p role="status" className="muted" style={{ margin: 0 }}>Loading instructions…</p>}
      {load.status === 'error' && <p role="alert" style={{ margin: 0, color: 'var(--color-danger)' }}>{load.message}</p>}
      {load.status === 'ready' && <AutomationSetupBody data={load.data} mode={mode} copied={copied} copyError={copyError} onCopy={(w, t) => void onCopy(w, t)} onNewRun={() => setVersion((n) => n + 1)} automation={automation} />}
    </Dialog>
  );
}
