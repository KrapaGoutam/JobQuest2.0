-- =============================================================================
-- AI-8: human-approved controlled actions (additive; NO core table changes)
--
-- AI proposes (ai_suggestions) -> JobQuest previews -> the human confirms in the UI ->
-- JobQuest revalidates and performs the mutation with the EXISTING core paths (RLS inserts
-- for applications / tasks, rpc_move_application_stage / rpc_set_application_outcome for
-- status) acting AS THE CALLER -> this table records the approval/execution provenance.
--
--   ai_action_executions : durable AI-specific provenance of each human-approved action.
--     Core audit stays authoritative for the record mutation itself (application_events
--     CREATED / STAGE_CHANGED / OUTCOME_CHANGED); this table says "who approved which
--     suggestion, what it targeted, and how it ended". Safe snapshots only (no provider
--     payloads, no secrets).
--
-- Access boundary:
--   * authenticated: SELECT only, same predicate as the parent AI rows
--     (public.can_access_owned_record). No client INSERT/UPDATE/DELETE.
--   * Writers: rpc_ai_action_claim / rpc_ai_action_complete (service_role only). The API
--     passes the actor id it derived from the verified session; the RPCs re-check that the
--     actor owns the suggestion and is an ACTIVE member of the workspace.
--   * rpc_ai_apply_status_change is SECURITY INVOKER (runs as the caller, RLS applies) and
--     only adds an atomic expected-state guard around the existing status RPCs.
--   * ai_suggestions.action vocabulary is unchanged: create_application, create_task and
--     set_status already exist in the AI-1A CHECK.
-- =============================================================================

-- 1. ai_action_executions
create table public.ai_action_executions (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references public.user_accounts(user_id) on delete cascade,
  suggestion_id uuid not null references public.ai_suggestions(id) on delete cascade,
  finding_id uuid not null references public.ai_findings(id) on delete cascade,
  action_type varchar(32) not null,
  target_type varchar(16) null,
  -- Pre-generated by the server before the core mutation so a crash between "mutate" and
  -- "record" can be reconciled deterministically (the record either exists or it does not).
  target_id uuid null,
  status varchar(12) not null default 'PENDING',
  -- Server-owned: sha256(workspace | suggestion | action | logical target). Never client-supplied.
  idempotency_key varchar(64) not null,
  state_fingerprint varchar(64) not null,
  before_snapshot jsonb not null default '{}'::jsonb,
  after_snapshot jsonb not null default '{}'::jsonb,
  error_category varchar(32) null,
  correlation_id varchar(64) null,
  requested_at timestamptz not null default now(),
  completed_at timestamptz null,
  constraint chk_ai_action_exec_action check (action_type in ('create_application', 'create_task', 'set_status')),
  constraint chk_ai_action_exec_target_type check (target_type is null or target_type in ('application', 'task')),
  constraint chk_ai_action_exec_status check (status in ('PENDING', 'SUCCEEDED', 'FAILED', 'CONFLICT')),
  constraint chk_ai_action_exec_error check (
    error_category is null or error_category in (
      'ACTION_NOT_SUPPORTED', 'ACTION_UNAUTHORIZED', 'ACTION_STALE', 'ACTION_AMBIGUOUS', 'ACTION_ALREADY_EXECUTED',
      'ACTION_TARGET_NOT_FOUND', 'ACTION_VALIDATION_FAILED', 'ACTION_CONFLICT', 'ACTION_EXECUTION_FAILED'
    )
  ),
  constraint chk_ai_action_exec_snapshots check (jsonb_typeof(before_snapshot) = 'object' and jsonb_typeof(after_snapshot) = 'object'),
  constraint chk_ai_action_exec_snapshot_size check (octet_length(before_snapshot::text) <= 4096 and octet_length(after_snapshot::text) <= 4096),
  constraint chk_ai_action_exec_completed check ((status = 'PENDING') = (completed_at is null))
);

-- Idempotency: at most ONE live (PENDING or SUCCEEDED) execution per logical action. A FAILED / CONFLICT
-- row never blocks a deliberate retry after the human re-reviews.
create unique index uq_ai_action_exec_live_key
  on public.ai_action_executions (workspace_id, idempotency_key)
  where status in ('PENDING', 'SUCCEEDED');
-- One live execution per suggestion (a repeated click / retry / second tab can never run it twice).
create unique index uq_ai_action_exec_live_suggestion
  on public.ai_action_executions (suggestion_id)
  where status in ('PENDING', 'SUCCEEDED');
-- A job lead becomes an Application at most once, however many suggestions propose it.
create unique index uq_ai_action_exec_live_conversion
  on public.ai_action_executions (finding_id)
  where action_type = 'create_application' and status in ('PENDING', 'SUCCEEDED');
create index idx_ai_action_exec_owner_recent
  on public.ai_action_executions (workspace_id, user_id, requested_at desc, id desc);

alter table public.ai_action_executions enable row level security;
revoke all on public.ai_action_executions from public, anon, authenticated;
grant select on public.ai_action_executions to authenticated;
grant select, insert, update, delete on public.ai_action_executions to service_role;

create policy ai_action_executions_select on public.ai_action_executions
  for select to authenticated
  using (public.can_access_owned_record(workspace_id, user_id));

-- 2. Claim: the idempotency gate. Serialised per suggestion (row lock) so concurrent confirms resolve to ONE winner.
--    outcome: claimed | already_succeeded | in_progress | stale_pending
create or replace function public.rpc_ai_action_claim(
  p_actor_id uuid,
  p_suggestion_id uuid,
  p_action_type text,
  p_target_type text,
  p_target_id uuid,
  p_idempotency_key text,
  p_fingerprint text,
  p_before jsonb,
  p_correlation_id text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_s public.ai_suggestions%rowtype;
  v_f public.ai_findings%rowtype;
  v_live public.ai_action_executions%rowtype;
  v_id uuid;
  v_fid uuid;
begin
  -- Lock order everywhere: finding, then suggestion (complete takes the same order), so claim and complete cannot deadlock.
  select s.finding_id into v_fid from public.ai_suggestions s
  where s.id = p_suggestion_id and s.user_id = p_actor_id;
  if not found then
    raise exception 'AI_SUGGESTION_NOT_FOUND' using errcode = 'P0002';
  end if;
  select * into v_f from public.ai_findings f where f.id = v_fid for update;
  select * into v_s from public.ai_suggestions s
  where s.id = p_suggestion_id and s.user_id = p_actor_id
  for update;
  if not found then
    raise exception 'AI_SUGGESTION_NOT_FOUND' using errcode = 'P0002';
  end if;
  perform app.ai_assert_actor(p_actor_id, v_s.workspace_id);
  if p_action_type is distinct from v_s.action or p_action_type not in ('create_application', 'create_task', 'set_status') then
    raise exception 'AI_ACTION_NOT_SUPPORTED' using errcode = '0A000';
  end if;
  if p_target_type is not null and p_target_type not in ('application', 'task') then
    raise exception 'AI_ACTION_INVALID' using errcode = '22023';
  end if;

  -- Replay of an already executed suggestion returns the recorded execution, never a second one.
  select * into v_live from public.ai_action_executions e
  where e.suggestion_id = v_s.id and e.status in ('PENDING', 'SUCCEEDED')
  limit 1;
  if found then
    if v_live.status = 'SUCCEEDED' then
      return jsonb_build_object('outcome', 'already_succeeded', 'execution_id', v_live.id,
        'target_type', v_live.target_type, 'target_id', v_live.target_id);
    end if;
    if v_live.requested_at > now() - interval '2 minutes' then
      return jsonb_build_object('outcome', 'in_progress', 'execution_id', v_live.id);
    end if;
    return jsonb_build_object('outcome', 'stale_pending', 'execution_id', v_live.id,
      'target_type', v_live.target_type, 'target_id', v_live.target_id);
  end if;

  if v_s.status <> 'PENDING' then
    raise exception 'AI_SUGGESTION_INVALID_TRANSITION' using errcode = '22023';
  end if;
  if v_f.status in ('DISMISSED', 'SUPERSEDED', 'EXPIRED') then
    raise exception 'AI_FINDING_CLOSED' using errcode = '22023';
  end if;

  -- Another suggestion may already have converted this lead.
  if p_action_type = 'create_application' then
    select * into v_live from public.ai_action_executions e
    where e.finding_id = v_f.id and e.action_type = 'create_application' and e.status in ('PENDING', 'SUCCEEDED')
    limit 1;
    if found then
      return jsonb_build_object(
        'outcome', case when v_live.status = 'SUCCEEDED' then 'already_succeeded'
                        when v_live.requested_at > now() - interval '2 minutes' then 'in_progress'
                        else 'stale_pending' end,
        'execution_id', v_live.id, 'target_type', v_live.target_type, 'target_id', v_live.target_id);
    end if;
  end if;

  insert into public.ai_action_executions (
    workspace_id, user_id, suggestion_id, finding_id, action_type, target_type, target_id,
    idempotency_key, state_fingerprint, before_snapshot, correlation_id
  ) values (
    v_s.workspace_id, p_actor_id, v_s.id, v_f.id, p_action_type, p_target_type, p_target_id,
    p_idempotency_key, p_fingerprint, coalesce(p_before, '{}'::jsonb), left(p_correlation_id, 64)
  )
  returning id into v_id;
  return jsonb_build_object('outcome', 'claimed', 'execution_id', v_id);
end;
$$;

-- 3. Complete: records the terminal state. On SUCCEEDED it also closes the suggestion and (for a job-lead
--    conversion) links the finding to the Application JobQuest created. Idempotent for a terminal execution.
create or replace function public.rpc_ai_action_complete(
  p_actor_id uuid,
  p_execution_id uuid,
  p_status text,
  p_target_type text,
  p_target_id uuid,
  p_after jsonb,
  p_error_category text,
  p_result text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_e public.ai_action_executions%rowtype;
begin
  if p_status not in ('SUCCEEDED', 'FAILED', 'CONFLICT') then
    raise exception 'AI_ACTION_INVALID' using errcode = '22023';
  end if;
  select * into v_e from public.ai_action_executions e
  where e.id = p_execution_id and e.user_id = p_actor_id
  for update;
  if not found then
    raise exception 'AI_ACTION_NOT_FOUND' using errcode = 'P0002';
  end if;
  perform app.ai_assert_actor(p_actor_id, v_e.workspace_id);
  if v_e.status <> 'PENDING' then
    return jsonb_build_object('execution_id', v_e.id, 'status', v_e.status, 'changed', false);
  end if;
  -- same lock order as claim: finding before suggestions
  perform 1 from public.ai_findings f where f.id = v_e.finding_id for update;

  update public.ai_action_executions e set
    status = p_status,
    target_type = coalesce(p_target_type, e.target_type),
    target_id = coalesce(p_target_id, e.target_id),
    after_snapshot = coalesce(p_after, '{}'::jsonb),
    error_category = case when p_status = 'SUCCEEDED' then null else p_error_category end,
    completed_at = now()
  where e.id = v_e.id;

  if p_status = 'SUCCEEDED' then
    update public.ai_suggestions s set
      status = 'ACCEPTED', decided_by = p_actor_id, decided_at = now(),
      applied_ref = jsonb_build_object('execution_id', v_e.id, 'action', v_e.action_type,
        'target_type', coalesce(p_target_type, v_e.target_type), 'target_id', coalesce(p_target_id, v_e.target_id),
        'result', left(p_result, 32))
    -- an Ignore that raced the mutation does not hide the fact that it happened
    where s.id = v_e.suggestion_id and s.status in ('PENDING', 'IGNORED');
    if v_e.action_type = 'create_application' then
      -- Trusted link: written here, after JobQuest created (or the human chose) the Application; never provider-supplied.
      update public.ai_findings f set
        application_id = coalesce(p_target_id, v_e.target_id), match_confidence = 1, status = 'ACCEPTED'
      where f.id = v_e.finding_id and exists (
        select 1 from public.applications a where a.id = coalesce(p_target_id, v_e.target_id) and a.workspace_id = v_e.workspace_id);
      -- Any other open proposal to convert the same lead is now moot: it can never create a second Application.
      update public.ai_suggestions s set status = 'SUPERSEDED'
      where s.finding_id = v_e.finding_id and s.action = 'create_application' and s.status = 'PENDING' and s.id <> v_e.suggestion_id;
    end if;
  end if;

  perform app.ai_write_audit(v_e.workspace_id, p_actor_id, v_e.user_id, 'AI_ACTION', v_e.id,
    case p_status when 'SUCCEEDED' then 'AI_ACTION_EXECUTED' when 'CONFLICT' then 'AI_ACTION_CONFLICT' else 'AI_ACTION_FAILED' end,
    jsonb_build_object('actor_kind', 'USER', 'action', v_e.action_type, 'suggestion_id', v_e.suggestion_id,
      'finding_id', v_e.finding_id, 'target_type', coalesce(p_target_type, v_e.target_type),
      'target_id', coalesce(p_target_id, v_e.target_id), 'result', left(p_result, 32), 'error_category', p_error_category));
  return jsonb_build_object('execution_id', v_e.id, 'status', p_status, 'changed', true);
end;
$$;

-- 4. Atomic compare-and-apply for a status change. SECURITY INVOKER: runs as the signed-in user, so RLS and the
--    existing RPCs' own authorization apply unchanged (no AI privilege). The row lock plus the expected-version
--    comparison make "stale preview" a database guarantee instead of a read-then-write race.
create or replace function public.rpc_ai_apply_status_change(
  p_application_id uuid,
  p_expected_updated_at timestamptz,
  p_new_stage text default null,
  p_new_outcome text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_app public.applications%rowtype;
  v_result jsonb;
begin
  if (p_new_stage is null) = (p_new_outcome is null) then
    raise exception 'AI_ACTION_INVALID' using errcode = '22023';
  end if;
  select * into v_app from public.applications a where a.id = p_application_id for update;
  if not found then
    raise exception 'APPLICATION_NOT_FOUND' using errcode = 'P0002';
  end if;
  if v_app.updated_at is distinct from p_expected_updated_at then
    raise exception 'ACTION_STALE' using errcode = 'P0001';
  end if;
  if v_app.archived_at is not null or v_app.status <> 'OPEN' then
    raise exception 'ACTION_CONFLICT' using errcode = '22023';
  end if;
  if p_new_outcome is not null then
    if p_new_outcome <> 'REJECTED' then
      raise exception 'AI_ACTION_INVALID' using errcode = '22023';
    end if;
    v_result := public.rpc_set_application_outcome(p_application_id, 'REJECTED', null, null);
  else
    v_result := public.rpc_move_application_stage(p_application_id, p_new_stage, null);
  end if;
  return v_result;
end;
$$;

-- 5. Explicit EXECUTE boundaries (Supabase default privileges grant EXECUTE to anon/authenticated).
revoke all on function public.rpc_ai_action_claim(uuid, uuid, text, text, uuid, text, text, jsonb, text) from public, anon, authenticated;
revoke all on function public.rpc_ai_action_complete(uuid, uuid, text, text, uuid, jsonb, text, text) from public, anon, authenticated;
revoke all on function public.rpc_ai_apply_status_change(uuid, timestamptz, text, text) from public, anon;
grant execute on function public.rpc_ai_action_claim(uuid, uuid, text, text, uuid, text, text, jsonb, text) to service_role;
grant execute on function public.rpc_ai_action_complete(uuid, uuid, text, text, uuid, jsonb, text, text) to service_role;
grant execute on function public.rpc_ai_apply_status_change(uuid, timestamptz, text, text) to authenticated;
