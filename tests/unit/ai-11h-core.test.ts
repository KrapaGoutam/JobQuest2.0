describe('automation analytics (Part C)', () => {
  const r = (over: Partial<AnalyticsRun> = {}): AnalyticsRun => ({
    id: Math.random().toString(36).slice(2), automationId: 'a1', provider: 'claude', workflow: 'daily_brief', status: 'SUCCEEDED', trigger: 'scheduled',
    createdAt: '2026-10-10T13:00:00Z', startedAt: '2026-10-10T13:00:00Z', completedAt: '2026-10-10T13:02:00Z', errorCategory: null, sources: [], ...over,
  });
  it('is honest about an empty window', () => {
    expect(summarizeAutomationRuns([], 30)).toMatchObject({ totalRuns: 0, successRate: null, avgCompletionMs: null, recentFailures: [], sourceProblems: { total: 0 } });
  });
  it('counts success, partial and failure separately; success rate is succeeded / finished', () => {
    const a = summarizeAutomationRuns([r(), r(), r({ status: 'PARTIAL' }), r({ status: 'FAILED', errorCategory: 'TIMEOUT' }), r({ status: 'RUNNING', completedAt: null })], 30);
    expect(a).toMatchObject({ totalRuns: 5, finishedRuns: 4, inFlightRuns: 1, succeeded: 2, partial: 1, failed: 1, successRate: 0.5 });
  });
  it('manual vs scheduled vs retry, retry recovery, provider and workflow breakdown, average duration', () => {
    const a = summarizeAutomationRuns([
      r(), r({ trigger: 'manual', provider: 'gemini', workflow: 'email_triage' }), r({ trigger: 'retry', status: 'SUCCEEDED' }), r({ trigger: 'retry', status: 'FAILED' }),
    ], 7);
    expect(a.byTrigger).toEqual({ scheduled: 1, manual: 1, retry: 2 });
    expect(a.retries).toEqual({ attempts: 2, recovered: 1 });
    expect(a.byProvider.map((x) => x.key)).toEqual(['claude', 'gemini']);
    expect(a.byWorkflow.find((x) => x.key === 'email_triage')).toMatchObject({ runs: 1, succeeded: 1 });
    expect(a.avgCompletionMs).toBe(120_000);
  });
  it('source problems count unavailable / blocked / error, never zero or skipped; recent failures are bounded, newest first, without error detail', () => {
    const a = summarizeAutomationRuns([
      r({ sources: [{ type: 'gmail', status: 'unavailable' }, { type: 'job_site', status: 'zero' }, { type: 'web', status: 'blocked' }] }),
      r({ sources: [{ type: 'gmail', status: 'error' }, { type: 'calendar', status: 'skipped' }] }),
      ...Array.from({ length: 8 }, (_, i) => r({ id: `f${i}`, status: 'FAILED', createdAt: `2026-10-0${i + 1}T10:00:00Z`, completedAt: `2026-10-0${i + 1}T10:01:00Z`, errorCategory: 'INTERNAL' })),
    ], 30);
    expect(a.sourceProblems).toEqual({ total: 3, byType: [{ key: 'gmail', count: 2 }, { key: 'web', count: 1 }] });
    expect(a.recentFailures).toHaveLength(5);
    expect(a.recentFailures[0]!.runId).toBe('f7');
    expect(JSON.stringify(a)).not.toMatch(/error_detail|errorDetail/);
  });
  it('attribution: a claim-linked run belongs to its automation; an unlinked provider run matches by workflow + provider; others to none', () => {
    const list = [{ id: 'a1', provider: 'claude' as const, workflow: 'daily_brief' as const }];
    expect(attributeRun({ automation_id: 'a1', provider: 'claude', workflow: 'daily_brief' }, list)).toBe('a1');
    expect(attributeRun({ automation_id: null, provider: 'claude', workflow: 'daily_brief' }, list)).toBe('a1');
    expect(attributeRun({ automation_id: null, provider: 'gemini', workflow: 'daily_brief' }, list)).toBeNull();
    expect(attributeRun({ automation_id: 'deleted', provider: 'claude', workflow: 'daily_brief' }, list)).toBeNull();
  });
});

describe('Weekly Digest boundaries (Part A)', () => {
  it('weeks start on the owner’s setting: Monday by default, Sunday when chosen', () => {
    expect(toWeekStartDay(undefined)).toBe(1);
    expect(toWeekStartDay(0)).toBe(0);
    expect(weekStartOf('2026-10-14')).toBe('2026-10-12'); // Wednesday -> Monday
    expect(weekStartOf('2026-10-12')).toBe('2026-10-12');
    expect(weekStartOf('2026-10-18')).toBe('2026-10-12'); // Sunday belongs to the Monday week
    expect(weekStartOf('2026-10-18', 0)).toBe('2026-10-18'); // ...but starts a week for a Sunday-start owner
    expect(weekStartOf('2026-10-14', 0)).toBe('2026-10-11');
    expect(weekEndOf('2026-10-12')).toBe('2026-10-18');
    expect(isWeekStart('2026-10-12') && !isWeekStart('2026-10-13') && isWeekStart('2026-10-11', 0)).toBe(true);
    expect(weeksBetween('2026-09-28', '2026-10-12')).toBe(2);
  });
  it('the "current week" follows the OWNER’s zone, not UTC', () => {
    // Monday 00:30 UTC is still Sunday evening in Chicago: the current week is the previous one there, and the new one in Berlin.
    const now = new Date('2026-10-12T00:30:00Z');
    expect(resolveWeek(now, 'America/Chicago', 1)).toMatchObject({ ok: true, weekStart: '2026-10-05', currentWeekStart: '2026-10-05' });
    expect(resolveWeek(now, 'Europe/Berlin', 1)).toMatchObject({ ok: true, weekStart: '2026-10-12' });
    expect(resolveWeek(now, 'UTC', 1)).toMatchObject({ ok: true, weekStart: '2026-10-12' });
    expect(resolveWeek(now, 'Not/AZone', 1)).toMatchObject({ ok: true, weekStart: '2026-10-12' }); // falls back to UTC
  });
  it('only a real, past, bounded week start is accepted', () => {
    const now = new Date('2026-10-14T15:00:00Z');
    expect(resolveWeek(now, 'America/Chicago', 1, '2026-10-05')).toMatchObject({ ok: true, weekStart: '2026-10-05' });
    expect(resolveWeek(now, 'America/Chicago', 1, '2026-10-06')).toMatchObject({ ok: false }); // not a week start
    expect(resolveWeek(now, 'America/Chicago', 1, '2026-10-19')).toMatchObject({ ok: false }); // future
    expect(resolveWeek(now, 'America/Chicago', 1, '2026-02-30')).toMatchObject({ ok: false }); // not a date
    expect(resolveWeek(now, 'America/Chicago', 1, '2026-04-13')).toMatchObject({ ok: true }); // 26 weeks back
    expect(resolveWeek(now, 'America/Chicago', 1, '2026-04-06')).toMatchObject({ ok: false }); // 27 weeks back
  });
  it('DST: the window is local midnight to local midnight, so a fall-back week is 169 hours and a spring-forward week 167', () => {
    const hours = (weekStart: string, next: string) => (Date.parse(localDayWindow(next, 'America/Chicago').start) - Date.parse(localDayWindow(weekStart, 'America/Chicago').start)) / 3_600_000;
    expect(hours('2026-10-26', '2026-11-02')).toBe(169); // fall back Nov 1 2026
    expect(hours('2027-03-08', '2027-03-15')).toBe(167); // spring forward Mar 14 2027
    expect(hours('2026-10-12', '2026-10-19')).toBe(168);
  });
});

describe('Weekly Digest composition (Part A)', () => {
  const base = (over: Partial<WeeklyInput> = {}): WeeklyInput => ({
    weekStart: '2026-10-05', currentWeekStart: '2026-10-12', timeZone: 'America/Chicago', windowStart: '2026-10-05T05:00:00.000Z', windowEnd: '2026-10-12T05:00:00.000Z',
    now: new Date('2026-10-14T15:00:00Z'), includeAttention: true, includeAutomationNow: false,
    applications: { added: 0, items: [] }, stage: { changes: 0, outcomes: 0, items: [], truncated: false }, interviews: { count: 0, items: [] },
    email: { health: 'ok', job: 0, other: 0, needsAction: 0, high: 0, items: [] }, leads: { health: 'ok', count: 0, strong: 0, items: [] },
    recruiters: { health: 'ok', count: 0, verified: 0, items: [] }, tasks: { completed: 0, openDue: 0, items: [] }, goals: [],
    automations: { configured: 0, runs: { total: 0, succeeded: 0, partial: 0, failed: 0, scheduled: 0, manual: 0, retry: 0, sourceProblems: 0 }, attention: null },
    attention: { interviews: [], interviewCount: 0, tasks: [], taskCount: 0, overdueTasks: 0, followUps: [], followUpCount: 0, emailsNeedingAction: 0 },
    ...over,
  });
  const section = (d: ReturnType<typeof composeWeeklyDigest>, k: string) => d.sections.find((s) => s.key === k)!;

  it('always lists the ten sections in order (attention only when applicable) and states the week honestly', () => {
    const d = composeWeeklyDigest(base());
    expect(d.sections.map((s) => s.key)).toEqual(['at_a_glance', 'applications', 'interviews', 'job_email', 'job_leads', 'recruiters', 'tasks', 'goals', 'automation_health', 'attention_next']);
    expect(d).toMatchObject({ weekStart: '2026-10-05', weekEnd: '2026-10-11', inProgress: false, throughAt: '2026-10-12T05:00:00.000Z', timeZone: 'America/Chicago', oldestWeekStart: '2026-04-13' });
    expect(composeWeeklyDigest(base({ includeAttention: false })).sections.map((s) => s.key)).not.toContain('attention_next');
    const running = composeWeeklyDigest(base({ weekStart: '2026-10-12', windowStart: '2026-10-12T05:00:00.000Z', windowEnd: '2026-10-19T05:00:00.000Z' }));
    expect(running.inProgress).toBe(true);
    expect(running.throughAt).toBe('2026-10-14T15:00:00.000Z');
  });
  it('an empty week is a clean empty state, never fabricated data', () => {
    const d = composeWeeklyDigest(base());
    expect(section(d, 'at_a_glance')).toMatchObject({ status: 'zero' });
    expect(section(d, 'at_a_glance').headline).toMatch(/quiet week/);
    expect(section(d, 'applications')).toMatchObject({ status: 'zero', count: 0, items: [] });
    expect(section(d, 'goals').status).toBe('not_configured');
    expect(section(d, 'automation_health').status).toBe('not_configured');
    expect(section(d, 'attention_next')).toMatchObject({ status: 'zero' });
  });
  it('zero vs unavailable vs not configured follows the source health (the Daily Digest rule)', () => {
    const d = composeWeeklyDigest(base({
      email: { health: 'failed', job: 0, other: 0, needsAction: 0, high: 0, items: [] },
      leads: { health: 'never', count: 0, strong: 0, items: [] },
      recruiters: { health: 'ok', count: 0, verified: 0, items: [] },
    }));
    expect(section(d, 'job_email')).toMatchObject({ status: 'unavailable', count: null, metrics: [] });
    expect(section(d, 'job_email').headline).toMatch(/unknown, not zero/);
    expect(section(d, 'job_leads').status).toBe('not_configured');
    expect(section(d, 'recruiters').status).toBe('zero');
    const glance = section(d, 'at_a_glance');
    expect(glance.metrics.find((m) => m.label === 'Job-related emails')!.value).toBe('unavailable');
    expect(glance.headline).toMatch(/could not be checked/);
  });
  it('summarises real activity, bounds items and keeps goal progress as measured', () => {
    const items = Array.from({ length: 9 }, (_, i) => ({ label: `Co${i} — Role`, stage: 'APPLIED', at: '2026-10-06T15:00:00Z' }));
    const d = composeWeeklyDigest(base({
      applications: { added: 9, items },
      interviews: { count: 2, items: [{ label: 'Acme — Staff', type: 'TECHNICAL', at: '2026-10-07T15:00:00Z' }] },
      stage: { changes: 3, outcomes: 1, truncated: false, items: [{ label: 'Acme — Staff', from: 'APPLIED', to: 'SCREEN', at: '2026-10-07T15:00:00Z' }] },
      email: { health: 'ok', job: 12, other: 3, needsAction: 2, high: 1, items: [{ title: 'Acme: Interview times', urgency: 'HIGH', action: 'Reply', at: null }] },
      goals: [{ type: 'APPLICATIONS', target: 15, actual: 9 }, { type: 'NETWORKING', target: 3, actual: 3 }],
      automations: { configured: 2, runs: { total: 7, succeeded: 5, partial: 1, failed: 1, scheduled: 5, manual: 1, retry: 1, sourceProblems: 2 }, attention: [{ name: 'Morning', label: 'Needs attention', reason: 'The provider credential has expired.' }] },
      includeAutomationNow: true,
    }));
    expect(section(d, 'applications').items).toHaveLength(6);
    expect(section(d, 'applications').headline).toBe('9 applications submitted.');
    expect(section(d, 'interviews').count).toBe(5);
    expect(section(d, 'job_email').headline).toMatch(/12 job-related emails.*3 other.*2 still need action/);
    expect(section(d, 'goals').items.map((i) => i.title)).toEqual(['Applications: 9 of 15', 'Networking: 3 of 3']);
    expect(section(d, 'goals').items[1]!.detail).toMatch(/met/);
    expect(section(d, 'automation_health').headline).toBe('7 automation runs: 5 succeeded, 1 partial, 1 failed.');
    expect(section(d, 'automation_health').items[0]!.detail).toMatch(/as of now/);
    expect(d.notes.join(' ')).toMatch(/as of now/);
  });
  it('a goal engine that cannot be read is unavailable, not "no goals"', () => {
    const d = composeWeeklyDigest(base({ goals: null }));
    expect(section(d, 'goals')).toMatchObject({ status: 'unavailable', count: null });
  });
  it('truncated stage history says "at least" instead of presenting a false exact number', () => {
    const d = composeWeeklyDigest(base({ stage: { changes: 300, outcomes: 0, truncated: true, items: [] } }));
    expect(section(d, 'interviews').metrics.find((m) => m.label === 'Stage changes')!.value).toBe('at least 300');
  });
  it('is deterministic and contains no secrets or raw bodies', () => {
    expect(JSON.stringify(composeWeeklyDigest(base()))).toBe(JSON.stringify(composeWeeklyDigest(base())));
    expect(JSON.stringify(composeWeeklyDigest(base()))).not.toMatch(/Bearer|jq_mcp_|service_role|client_secret/i);
  });
});
