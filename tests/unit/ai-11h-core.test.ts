describe('stable manual client key (Part E)', () => {
  it('is a valid claim key, generated by JobQuest, never derived from a clock', () => {
    const keys = new Set(Array.from({ length: 200 }, () => mintManualClientKey()));
    expect(keys.size).toBe(200);
    for (const k of keys) { expect(k).toMatch(CLIENT_KEY); expect(k).not.toMatch(/^manual-/); }
    expect(mintManualClientKey(() => 'aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee')).toBe('maaaaaaaabbbb4ccc8ddd');
  });
  it('embeds ONE key verbatim in the run-once text; the same text is the same run, new instructions are a new run', () => {
    const first = buildSchedulerSetup(auto())!;
    expect(first.manualRunInstructions).toContain(`"clientKey": "${first.manualRunKey}"`);
    expect(first.manualRunInstructions).toMatch(/copy this clientKey EXACTLY/);
    expect(first.manualRunInstructions).not.toMatch(/current UTC time|YYYYMMDD|manual-</);
    const again = buildSchedulerSetup(auto(), first.manualRunKey)!;
    expect(again.manualRunInstructions).toBe(first.manualRunInstructions); // re-pasting identical text = identical claim
    expect(buildSchedulerSetup(auto())!.manualRunKey).not.toBe(first.manualRunKey);
  });
  it('never touches the scheduled path: no client key in scheduled instructions, scheduled occurrence keys are unchanged', () => {
    const s = buildSchedulerSetup(auto(), 'm1234567890abcdef1234')!;
    expect(s.scheduledInstructions).not.toMatch(/clientKey|m1234567890abcdef1234/);
    const src = readFileSync('apps/api/src/lib/aiContract/automation.ts', 'utf8');
    expect(src).toMatch(/auto:\$\{/); // scheduled occurrence identity still derived from the UTC occurrence, not from any client key
  });
  it('refuses an invalid key and keeps the text free of secrets', () => {
    expect(() => buildSchedulerSetup(auto(), 'short')).toThrow();
    expect(() => buildSchedulerSetup(auto(), 'has spaces and !!')).toThrow();
    expect(JSON.stringify(buildSchedulerSetup(auto()))).not.toMatch(/jq_mcp_|Bearer [A-Za-z0-9]|client_secret|service_role|eyJ/i);
  });
});

describe('automation health (Part B)', () => {
  const NOW = new Date('2026-10-14T15:00:00Z');
  const run = (over: Partial<HealthRun> = {}): HealthRun => ({
    id: 'r1', status: 'SUCCEEDED', trigger: 'scheduled', createdAt: '2026-10-14T13:00:00Z', startedAt: '2026-10-14T13:00:05Z', completedAt: '2026-10-14T13:02:00Z', errorCategory: null, retryAttempt: null, ...over,
  });
  const ready = { connection: 'connected' as const, canIngest: true, credential: 'active' as const, scheduler: 'READY' as const };
  const input = (over: Partial<HealthInput> = {}): HealthInput => ({
    enabled: true, provider: 'claude', cadence: 'weekdays', nextExpectedRunAt: '2026-10-15T13:00:00Z', runs: [run()], providerStatus: ready, now: NOW, ...over,
  });

  it('disabled is never an intervention; healthy needs nothing', () => {
    expect(deriveAutomationHealth(input({ enabled: false, runs: [run({ status: 'FAILED' })] }))).toMatchObject({ state: 'disabled', label: 'Disabled', interventionRequired: false, nextExpectedRunAt: null });
    expect(deriveAutomationHealth(input())).toMatchObject({ state: 'healthy', label: 'Healthy', interventionRequired: false, lastTrigger: 'scheduled' });
  });
  it('failed or partial last run needs attention; running wins; never run is its own state', () => {
    expect(deriveAutomationHealth(input({ runs: [run({ status: 'FAILED', errorCategory: 'SOURCE_UNAVAILABLE' })] }))).toMatchObject({ state: 'needs_attention', interventionRequired: true });
    expect(deriveAutomationHealth(input({ runs: [run({ status: 'PARTIAL' })] })).state).toBe('needs_attention');
    expect(deriveAutomationHealth(input({ runs: [run({ status: 'RUNNING', completedAt: null, startedAt: '2026-10-14T14:30:00Z' })] })).state).toBe('running');
    expect(deriveAutomationHealth(input({ runs: [] })).state).toBe('never_run');
    expect(deriveAutomationHealth(input({ runs: [], cadence: 'manual_only', provider: 'manual', providerStatus: null })).state).toBe('never_run');
  });
  it('a claim that never reported back is attention, not "running"', () => {
    const h = deriveAutomationHealth(input({ runs: [run({ status: 'RUNNING', completedAt: null, startedAt: '2026-10-14T12:00:00Z' })] }));
    expect(h.state).toBe('needs_attention');
    expect(h.reasons.join(' ')).toMatch(/never reported back/);
  });
  it('provider problems: expired / revoked / read-only need attention, not connected needs setup, connected-without-a-schedule needs setup', () => {
    const p = (over: Record<string, unknown>) => ({ ...ready, ...over }) as HealthInput['providerStatus'];
    expect(deriveAutomationHealth(input({ providerStatus: p({ connection: 'not_connected', credential: 'expired', scheduler: 'NOT_CONNECTED' }) }))).toMatchObject({ state: 'needs_attention', interventionRequired: true });
    expect(deriveAutomationHealth(input({ providerStatus: p({ connection: 'not_connected', credential: 'revoked', scheduler: 'NOT_CONNECTED' }) })).reasons[0]).toMatch(/revoked/);
    expect(deriveAutomationHealth(input({ providerStatus: p({ connection: 'not_connected', credential: 'none', scheduler: 'NOT_CONNECTED' }), runs: [] })).state).toBe('needs_setup');
    expect(deriveAutomationHealth(input({ providerStatus: p({ canIngest: false, scheduler: 'NOT_CONNECTED' }) })).state).toBe('needs_attention');
    expect(deriveAutomationHealth(input({ providerStatus: p({ scheduler: 'SETUP_REQUIRED' }), runs: [] }))).toMatchObject({ state: 'needs_setup', interventionRequired: true });
    // a successful manual run does not mean the provider's schedule exists
    expect(deriveAutomationHealth(input({ providerStatus: p({ scheduler: 'SETUP_REQUIRED' }), runs: [run({ trigger: 'manual' })] })).state).toBe('needs_setup');
  });
  it('a past success is not contradicted by a provider that merely has no credential record (the failure is reported once, as the failure)', () => {
    const h = deriveAutomationHealth(input({ providerStatus: { connection: 'not_connected', canIngest: false, credential: 'none', scheduler: 'NOT_CONNECTED' } }));
    expect(h.state).toBe('healthy');
    expect(h.reasons.join(' ')).not.toMatch(/cannot save results|not connected/);
    const failed = deriveAutomationHealth(input({ runs: [run({ status: 'FAILED', errorCategory: 'SOURCE_UNAVAILABLE' })] }));
    expect(failed.reasons).toEqual(['The last run failed.']);
  });
  it('a lapsed credential outranks a past success (the NEXT run would fail)', () => {
    const h = deriveAutomationHealth(input({ providerStatus: { ...ready, connection: 'not_connected', credential: 'expired', scheduler: 'NOT_CONNECTED' } }));
    expect(h.state).toBe('needs_attention');
    expect(h.lastSuccessAt).not.toBeNull();
  });
  it('retry state: in flight, attempt number, exhausted', () => {
    expect(retryAttemptOf('retry:123e4567-e89b-42d3-a456-426614174000:2')).toBe(2);
    expect(retryAttemptOf('auto:abc')).toBeNull();
    const inflight = deriveAutomationHealth(input({ runs: [run({ id: 'r2', trigger: 'retry', status: 'RUNNING', completedAt: null, startedAt: '2026-10-14T14:50:00Z', retryAttempt: 2 }), run({ status: 'FAILED' })] }));
    expect(inflight).toMatchObject({ state: 'running', retry: { attempt: 2, inFlight: true, exhausted: false } });
    expect(inflight.reasons[0]).toMatch(/Retry attempt 2 of 3/);
    const done = deriveAutomationHealth(input({ runs: [run({ trigger: 'retry', status: 'FAILED', retryAttempt: AUTOMATION_RETRY_LIMIT })] }));
    expect(done).toMatchObject({ state: 'needs_attention', retry: { exhausted: true } });
  });
  it('provider-less automations are not blamed for provider readiness', () => {
    expect(deriveAutomationHealth(input({ provider: 'manual', cadence: 'manual_only', providerStatus: null })).state).toBe('healthy');
    expect(deriveAutomationHealth(input({ provider: 'manual', cadence: 'daily', providerStatus: null })).state).toBe('needs_setup');
  });
});

